import { runnerImport } from 'vite'
import { writeFileSync } from 'node:fs'

const { module: data } = await runnerImport('./src/data/hatchlings.ts', { configFile: false })
writeFileSync('src/data/catalogue-ids.ts', `// Generated by npm run catalogue from the shipped species.\nexport const CATALOGUE_IDS = ${JSON.stringify(Object.keys(data.EXTRA_PLAYABLE))} as const\n`)
writeFileSync('server/room-catalogue.json', `${JSON.stringify(data.PLAYABLE_IDS)}\n`)
console.log(`${data.PLAYABLE_IDS.length} playable Pokémon`)
